import assert from "node:assert/strict";
import fs from "node:fs";
const catalog=JSON.parse(fs.readFileSync("app/content/catalog.json","utf8")).entries;
const library=JSON.parse(fs.readFileSync("app/rules/rules-data.json","utf8")).books;
const entries=catalog.filter(entry=>entry.versions.some(version=>version.book==="companion-v5"));
const counts=Object.fromEntries(["clan","power","merit","flaw"].map(kind=>[kind,entries.filter(entry=>entry.kind===kind).length]));
assert.deepEqual(counts,{clan:3,power:10,merit:15,flaw:5});
const companion=library.find(book=>book.id==="companion-v5");
assert.deepEqual(companion.chapters.flatMap(chapter=>chapter.sourcePages.map(page=>page.pdfPage)),Array.from({length:68},(_,i)=>i+1));
const clanChapter=companion.chapters.find(chapter=>chapter.id==="companion-v5-parte-i-os-clas-e-suas-aptidoes");
assert.ok(clanChapter.content.includes("Saulot abriu enquanto realizava uma das suas muitas jornadas"));
assert.ok(clanChapter.content.includes("Qualquer ação que não seja realizada em função de mitigar aquela tragédia pessoal"));
const rulesChapter=companion.chapters.find(chapter=>chapter.id==="companion-v5-parte-iv-errata-e-atualizacao-de-regras");
const rows=rulesChapter.content.split("\n").filter(line=>/^\| \d+ \|/.test(line));assert.equal(rows.length,11);
const expected=[[1,1],[2,1],[2,2],[3,2],[3,3],[4,3],[4,3],[5,3],[5,4],[6,4],[6,5]];
rows.forEach((row,i)=>{const cells=row.split("|").slice(1,-1).map(cell=>cell.trim());assert.equal(Number(cells[0]),i);assert.equal(Number(cells[1].match(/\d+/)[0]),expected[i][0]);assert.equal(Number(cells[2].match(/\d+/)[0]),expected[i][1]);assert.equal(cells.length,7)});
const edition=(id,book)=>catalog.find(entry=>entry.id===id).versions.find(version=>version.book===book);
const text=(id,book,lang)=>edition(id,book).descriptions[lang].map(section=>section.text).join(" ");
assert.ok(text("players-guide-v5-power-proteanismo-one-with-the-land","companion-v5","pt-BR").includes("1,6 quilômetro"));
assert.ok(text("players-guide-v5-power-proteanismo-one-with-the-land","players-guide-v5","en").includes("roughly one kilometer"));
assert.ok(text("fata-morgana","players-guide-v5","pt-BR").includes("Dificuldade um ponto menor"));
assert.ok(!text("fata-morgana","companion-v5","pt-BR").includes("Dificuldade um ponto menor"));
assert.equal(edition("companion-advantage-weak-willed","companion-v5").level,3);
assert.equal(edition("companion-advantage-weak-willed","players-guide-v5").level,2);
assert.equal(edition("companion-advantage-living-on-the-edge","players-guide-v5").names.en,"Risk-Taker");
assert.equal(edition("companion-advantage-distressing-fangs","companion-v5").level,2);
assert.equal(edition("companion-advantage-distressing-fangs","players-guide-v5").level,1);
console.log("Companion: 33 character options, 68 pages, intact clan text, 11 potency rows and edition differences verified.");
